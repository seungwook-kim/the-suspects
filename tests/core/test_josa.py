import pytest

from server.game.josa import josa


@pytest.mark.parametrize("word,pair,out", [
    ("로비", "으로/로", "로비로"), ("서버실", "으로/로", "서버실로"), ("탕비실", "으로/로", "탕비실로"),
    ("1층 로비·보안데스크", "은/는", "1층 로비·보안데스크는"), ("지하 주차장", "은/는", "지하 주차장은"),
    ("황지호, 남궁철", "이/가", "황지호, 남궁철이"), ("황지호", "이/가", "황지호가"),
    ("'출입카드 기록'", "을/를", "'출입카드 기록'을"), ("'USB'", "을/를", "'USB'을(를)"),
    ("3층", "으로/로", "3층으로"), ("B1", "으로/로", "B1로"), ("API", "으로/로", "API(으)로"), ("2", "은/는", "2는"), ("7", "으로/로", "7로"),
])
def test_josa(word, pair, out):
    assert josa(word, pair) == out
